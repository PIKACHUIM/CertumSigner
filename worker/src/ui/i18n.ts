export function localizeError(t: Translate, message: string): string {
  const key = MESSAGE_KEYS[message.trim()];
  return key ? t(key) : message;
}

/** 从 Accept-Language 猜语言：任何以 zh 开头的 tag 都算中文，其余按英文 */
export function detectLang(acceptLanguage?: string | null): Lang {
  const header = (acceptLanguage ?? "").toLowerCase();
  if (!header) return "zh";
  const first = header.split(",")[0]?.trim() ?? "";
  return first.startsWith("zh") ? "zh" : "en";
}

export function normalizeLang(value?: string | null): Lang | null {
  const text = (value ?? "").toLowerCase();
  if (text === "zh" || text === "zh-cn" || text === "cn") return "zh";
  if (text === "en" || text === "en-us") return "en";
  return null;
}
